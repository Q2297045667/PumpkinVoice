//! Plugin translations, backed by Pumpkin's own host-side i18n registry.
//!
//! Pumpkin exposes its translation system to plugins through the `i18n` WIT
//! interface: a plugin registers flat JSON maps under a namespace
//! ([`i18n::load_translations`]), and `TextComponent::custom` components are
//! resolved by the host against that registry using the player's locale
//! before the text reaches the client. Missing translations fall back to
//! `en_us`, then to the raw key, so an incomplete language file can never
//! break a message.
//!
//! # Adding a language
//!
//! Drop a `lang/<locale>.json` file into the crate root (or, at runtime, into
//! `<plugin data folder>/lang/<locale>.json`) — no code changes required.
//! Embedded files are discovered by `build.rs`; data-folder files are scanned
//! on load and override the embedded ones.

use pumpkin_plugin_api::{common::Locale, i18n, text::TextComponent};
use std::fs;
use std::sync::OnceLock;

/// Namespace every plugin translation key lives under.
pub const NAMESPACE: &str = "pumpkin_voice";

/// Fallback if the configured server language cannot be read.
pub const FALLBACK_LOCALE: &str = "en_us";

// Auto-generated by build.rs: one entry per `lang/<locale>.json`.
include!(concat!(env!("OUT_DIR"), "/embedded_langs.rs"));

/// Server-side language (from the `language` config option), used for
/// registration-time strings (command and permission descriptions) and
/// console feedback. Player-facing messages always use the player's own
/// client locale instead.
static SERVER_LOCALE: OnceLock<String> = OnceLock::new();

/// Registers the embedded translations (and any overrides found in
/// `<data_folder>/lang/<locale>.json`) with the Pumpkin host.
///
/// Files loaded later overwrite earlier keys, so data-folder files override
/// the embedded defaults. Must be called once from `on_load` (after the
/// config is initialized) before any translated component is sent.
pub fn init(data_folder: &str) {
    let language = crate::config::CONFIG
        .read()
        .map(|config| config.language.clone())
        .unwrap_or_else(|_| FALLBACK_LOCALE.to_string());
    let _ = SERVER_LOCALE.set(language);

    for (locale, json) in EMBEDDED_LANGS {
        match locale_from_str(locale) {
            Some(wit_locale) => i18n::load_translations(NAMESPACE, json, wit_locale),
            None => tracing::warn!("Skipping embedded language file with unknown locale {locale}"),
        }
    }

    load_folder_overrides(data_folder);
}

/// The server-side language (config option `language`, default `en_us`).
#[must_use]
pub fn default_locale() -> &'static str {
    SERVER_LOCALE.get().map_or(FALLBACK_LOCALE, String::as_str)
}

/// Builds a translated text component for `key`, resolved in `locale`.
#[must_use]
pub fn tr(locale: &str, key: &str) -> TextComponent {
    TextComponent::custom(NAMESPACE, key, locale, Vec::new())
}

/// Builds a translated text component with sequential `%s` substitution
/// arguments.
#[must_use]
pub fn tr_with(locale: &str, key: &str, args: Vec<TextComponent>) -> TextComponent {
    TextComponent::custom(NAMESPACE, key, locale, args)
}

/// Resolves `key` to a plain translated string, for APIs that take raw
/// strings instead of text components (e.g. command and permission
/// descriptions, Bedrock kick messages).
#[must_use]
pub fn translate_str(locale: &str, key: &str) -> String {
    let locale = locale_from_str(locale).unwrap_or(Locale::EnUs);
    i18n::translate(&format!("{NAMESPACE}:{key}"), locale)
}

/// Loads `lang/<locale>.json` overrides from the plugin data folder.
fn load_folder_overrides(data_folder: &str) {
    let normalized = data_folder.replace('\\', "/");
    let cleaned = normalized.trim_matches('/');
    if cleaned.is_empty() {
        return;
    }

    let dir = std::path::Path::new(cleaned).join("lang");
    let Ok(entries) = fs::read_dir(&dir) else {
        return; // No overrides folder: perfectly normal.
    };

    for entry in entries.flatten() {
        let path = entry.path();
        if !path.is_file() || path.extension().and_then(|e| e.to_str()) != Some("json") {
            continue;
        }
        let Some(stem) = path.file_stem().and_then(|s| s.to_str()) else {
            continue;
        };
        let Some(locale) = locale_from_str(stem) else {
            tracing::warn!("Ignoring translation file with unsupported locale: {path:?}");
            continue;
        };
        match fs::read_to_string(&path) {
            Ok(json) => {
                i18n::load_translations(NAMESPACE, &json, locale);
                tracing::info!("Loaded voice chat translations for {stem} from {path:?}");
            }
            Err(err) => tracing::warn!("Failed to read translation file {path:?}: {err}"),
        }
    }
}

