#[cfg(test)]
mod tests {
    use super::{EMBEDDED_LANGS, locale_from_str};
    use std::collections::HashMap;

    fn parse(json: &str) -> HashMap<String, String> {
        serde_json::from_str(json).unwrap_or_else(|e| panic!("invalid language file: {e}"))
    }

    #[test]
    fn embedded_language_files_are_valid_and_non_empty() {
        // The host parses these with `unwrap_or_default`, so a broken file
        // would silently register zero translations.
        assert!(!EMBEDDED_LANGS.is_empty(), "no embedded language files found");
        for (locale, json) in EMBEDDED_LANGS {
            let map = parse(json);
            assert!(!map.is_empty(), "{locale} contains no translations");
        }
    }

    #[test]
    fn every_locale_defines_the_same_keys() {
        let (_, reference) = EMBEDDED_LANGS
            .iter()
            .find(|(locale, _)| *locale == "en_us")
            .expect("en_us.json is the fallback and must exist");
        let mut reference: Vec<_> = parse(reference).keys().cloned().collect();
        reference.sort_unstable();

        for (locale, json) in EMBEDDED_LANGS {
            let mut keys: Vec<_> = parse(json).keys().cloned().collect();
            keys.sort_unstable();
            assert_eq!(
                keys, reference,
                "translation keys in {locale} drifted from en_us"
            );
        }
    }

    #[test]
    fn every_embedded_locale_is_supported() {
        // A file named e.g. `en-US.json` would be silently skipped at load
        // time; catch that here instead.
        for (locale, _) in EMBEDDED_LANGS {
            assert!(
                locale_from_str(locale).is_some(),
                "unsupported locale file name: {locale}"
            );
        }
    }
}
